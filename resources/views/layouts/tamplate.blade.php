        function formatInputRibuan(el) {
            let value = el.value.replace(/\D/g, ''); // ambil angka saja
            el.value = value ? value.replace(/\B(?=(\d{3})+(?!\d))/g, ".") : '';
        }

        function formatRibuan(angka) {
            if (!angka) return '';
            return angka.toString().replace(/\D/g, '')
